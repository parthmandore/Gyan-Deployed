export const getGameRealm = (entryOrId: GameRegistryEntry | string): LearningRealm => {
  if (typeof entryOrId === 'string') {
    return GAME_REALM_MAPPING[entryOrId] || 'letters_phonics';
  }
  return entryOrId.realm || GAME_REALM_MAPPING[entryOrId.id] || 'letters_phonics';
};

