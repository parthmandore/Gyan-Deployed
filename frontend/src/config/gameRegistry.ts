export type LearningRealm =
  | 'letters_phonics'
  | 'reading_words'
  | 'vocabulary'
  | 'mathematics'
  | 'reasoning_logic'
  | 'shapes_colours'
  | 'grammar_syntax';

export interface GameRegistryEntry {
  id: string;
  titleKey: string;
  descriptionKey: string;
  iconAsset: string;
  bgColor: string;
  gradientColors: readonly [string, string, string];
  bevelColor: string;
  badgeTag: string;
  navigatorRoute: string;
  routeParams?: Record<string, string>;
  supportedLanguages: AppLanguage[];
  minimumAge: AppAge;
  maximumAge: AppAge;
  ageGroups: readonly AppAge[];
  realm?: LearningRealm;
}

